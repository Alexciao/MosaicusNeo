import { evaluate, describe } from '../toolbox/calculator-engine.js';
let fail = 0;
const t = (src, want, key = 'exact', ctx = {}, opts = {}) => {
  let got;
  try { got = describe(evaluate(src, ctx), opts)[key]; if (got && got.latex) got = got.latex; }
  catch (e) { got = 'ERR:' + e.code; }
  const ok = got === want;
  if (!ok) fail++;
  console.log(ok ? 'ok  ' : 'FAIL', src.padEnd(38), '→', got, ok ? '' : `   (wanted ${want})`);
};
t('\\frac{1}{2}+\\frac{1}{3}', '\\frac{5}{6}');
t('\\frac{3}{4}-\\frac{3}{4}', '0');
t('\\frac{7}{3}', '\\frac{7}{3}');
