t('\\frac{1}{6}', '0.1\\overline{6}', 'decimal');
t('\\frac{1}{7}', '0.\\overline{142857}', 'decimal');
t('\\frac{1}{4}', '0.25', 'decimal');
t('\\frac{1}{4}', '0{,}25', 'decimal', {}, { dec: ',' });
t('\\frac12+\\frac13', '\\frac{5}{6}');
t('0.1+0.2', '\\frac{3}{10}');
t('0.1+0.2', '0.3', 'decimal');
t('2\\times3+4', '10');
t('2+3\\cdot4^2', '50');
t('\\left(\\frac{2}{3}\\right)^{2}', '\\frac{4}{9}');
