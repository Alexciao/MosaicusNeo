t('2\\left(3+4\\right)', '14');
t('3\\sqrt{2}', '3\\sqrt{2}');
t('1,5+1', '\\frac{5}{2}');
t('1{,}5+1', '\\frac{5}{2}');
t('\\mathrm{Ans}+1', '\\frac{8}{3}', 'exact', { ans: evaluate('\\frac{5}{3}') });
t('\\mathrm{Ans}', 'ERR:noans');
t('\\frac{3}{4}\\times10^{-3}', '\\frac{3}{4000}');
